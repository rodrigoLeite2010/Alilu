import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import { beforeEach, it, expect, vi } from "vitest";
import { TravelPlanner } from "@/components/viagens/TravelPlanner";
vi.mock("@/components/layout/useHeaderAuth", () => ({ useHeaderAuth: () => ({ status: "signed-out" }) }));
beforeEach(() => { localStorage.clear(); });
it("permite calcular, gerar mala, reorganizar roteiro e restaurar rascunho sem login", async () => {
  render(<TravelPlanner />);
  fireEvent.change(screen.getByLabelText("Nome da viagem"), { target: { value: "Férias em família" } });
  fireEvent.change(screen.getByLabelText("Cidade de destino"), { target: { value: "Ubatuba, SP" } });
  fireEvent.change(screen.getByLabelText("Data de saída"), { target: { value: "2026-11-06" } });
  fireEvent.change(screen.getByLabelText("Fim da viagem / retorno"), { target: { value: "2026-11-08" } });
  expect(screen.getByText(/3 dia\(s\) e 2 noite\(s\)/)).toBeInTheDocument();
  fireEvent.click(screen.getByRole("button", { name: "2. Transporte" }));
  fireEvent.change(screen.getByLabelText("Distância manual de ida (km)"), { target: { value: "300" } });
  fireEvent.change(screen.getByLabelText("Consumo rodoviário / médio (km/L)"), { target: { value: "12" } });
  fireEvent.change(screen.getByLabelText("Preço por litro (R$)"), { target: { value: "6" } });
  fireEvent.change(screen.getByLabelText("Pedágios na ida (R$)"), { target: { value: "0" } });
  expect(screen.getByLabelText("Pedágios na ida (R$)")).toHaveValue(0);
  fireEvent.click(screen.getByRole("button", { name: "4. Checklist" }));
  fireEvent.click(screen.getByRole("button", { name: "Gerar checklist da viagem" }));
  expect(screen.getByLabelText("Descrição do item 1")).toHaveValue("Documento de identificação aceito no destino");
  fireEvent.click(screen.getByRole("button", { name: "5. Roteiro" }));
  fireEvent.click(screen.getByRole("button", { name: "+ Adicionar atividade" }));
  fireEvent.change(screen.getByLabelText("Dia da atividade"), { target: { value: "2" } });
  expect(screen.getByText(/Dia 2 · Horário livre/)).toBeInTheDocument();
  fireEvent.click(screen.getByText("Salvar e gerenciar minhas viagens"));
  fireEvent.click(screen.getByRole("button", { name: "Salvar rascunho neste dispositivo" }));
  await waitFor(() => expect(localStorage.getItem("alilu:viagem:rascunho:v1")).toContain("Férias em família"));
  fireEvent.change(screen.getByLabelText("Atividade"), { target: { value: "Alterado" } });
  fireEvent.click(screen.getByRole("button", { name: "Restaurar rascunho" }));
  expect(screen.getByLabelText("Atividade")).toHaveValue("Nova atividade");
});
